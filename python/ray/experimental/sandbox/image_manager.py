# The OCI capability sets written when `capabilities` is given (schema:
# https://github.com/opencontainers/runtime-spec/blob/main/config.md#linux-process).
# Modern Docker populates exactly these: "inheritable" was dropped by Docker
# for CVE-2022-24769, and "ambient" would survive into non-root execve'd
# children.
_OCI_CAPABILITY_SETS = ("bounding", "effective", "permitted")

_RESOLV_CONF = "/etc/resolv.conf"
_ETC_HOSTS = "/etc/hosts"

# How a cached image supplies a sandbox's rootfs: an EROFS image Ray pulls
# and builds, or a directory an image provider plugin streams.
MODE_EROFS = "erofs"
MODE_STREAMED = "streamed"
_IMAGE_CONFIG_FILE = ".image_config.json"
# The pin a pull without an instance takes on a streamed image, holding its
# plugin lease until the first sandbox to pull the image claims it.
_UNCLAIMED_USER = ".unclaimed"


def _is_local_archive(image: str) -> bool:
    return image.endswith(".tar") or image.startswith(("/", "./", "../"))


def _write_json_atomic(path: str, data: Dict[str, Any]) -> None:
    tmp = f"{path}.tmp.{os.getpid()}"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)
    os.replace(tmp, path)


def get_default_oci_spec() -> Dict[str, Any]:
    """Derive default OCI runtime specification by executing `runsc spec` in a temporary directory.

    Returns:
        Dictionary representation of the default OCI config.json generated by `runsc spec`.
    """
    from ray.experimental.sandbox.backend.gvisor import runsc_env

    with tempfile.TemporaryDirectory() as temp_dir:
        subprocess.run(["runsc", "spec"], cwd=temp_dir, check=True, env=runsc_env())
        config_path = os.path.join(temp_dir, "config.json")
        with open(config_path, "r", encoding="utf-8") as f:
            return json.load(f)


def _chain_transform_fns(
    *fns: Optional[Callable[[Dict[str, Any]], Optional[Dict[str, Any]]]],
) -> Callable[[Dict[str, Any]], Dict[str, Any]]:
    """Build an `_oci_spec_transform_fn` that applies `fns` (skipping any
    that are None) in order, each to the previous one's result.
    """
    active_fns = [fn for fn in fns if fn is not None]

    def _chained(spec: Dict[str, Any]) -> Dict[str, Any]:
        for fn in active_fns:
            result = fn(spec)
            if result is not None:
                spec = result
        return spec

    return _chained


def _build_gpu_cdi_devices_transform_fn(
    cdi_spec: cdi_lib.CDISpec,
    cdi_devices: List[Dict[str, Any]],
) -> Callable[[Dict[str, Any]], Dict[str, Any]]:
    """Build an `_oci_spec_transform_fn` that merges `cdi_devices`' CDI
    edits into whatever spec `create_oci_spec` passes it.
    """

    def _transform(spec: Dict[str, Any]) -> Dict[str, Any]:
        try:
            cdi_spec.apply_edits(spec, cdi_devices)
        except cdi_lib.CDIError as err:
            raise SandboxCreationError(
                f"Failed to configure GPU access via CDI: {err}"
            ) from err
        return spec

    return _transform


class BaseImageManager(ABC):
    """Abstract Base Class defining the contract for Container Image Managers.

    Image managers are responsible for acquiring container images (via registry pull,
    local archive extraction, or remote cache synchronization), providing metadata
    (such as working directory and environment variables), and generating standard OCI
    runtime specifications (bundles) for sandbox execution backends.
    """

    @abstractmethod
    def pull_image(
        self,
        image: str,
        timeout_seconds: float = 120.0,
        instance_id: Optional[str] = None,
    ) -> str:
        """Pull a container image into the local cache or storage.

        Args:
            image: Container image reference (e.g. 'python:3.10-slim') or path to local tar archive.
            timeout_seconds: Timeout for network operations.
            instance_id: The sandbox instance that will use the image. When
                given, the image is pinned in the cache until
                ``release_image`` is called for the same instance.

        Returns:
            Absolute path of the directory holding the cached image.
        """
        pass

    def release_image(self, image: str, instance_id: str) -> None:
        """Release an instance's pin on an image taken by ``pull_image``.

        Managers without a cache need not override this.

        Args:
            image: Container image reference or tar path passed to ``pull_image``.
            instance_id: The sandbox instance that no longer uses the image.
        """
        return None

    @abstractmethod
    def get_image_dir(self, image: str) -> str:
        """Get the cached local directory path for an image.

        Args:
            image: Container image name or tar path.

        Returns:
            Absolute directory path for the image cache directory.
        """
        pass

    @abstractmethod
    def get_image_config(self, image: str) -> Dict[str, Any]:
        """Read and parse the container image configuration metadata.

        Args:
            image: Container image name or tar path.

        Returns:
            Dictionary representation of container image configuration.
        """
        pass

    @abstractmethod
    def get_workdir(self, image: str) -> Optional[str]:
        """Extract the default WorkingDir from the container image configuration.

        Args:
            image: Container image name or tar path.

        Returns:
            Configured working directory string, or None if not specified.
        """
        pass

    @abstractmethod
    def get_envs(self, image: str) -> List[str]:
        """Extract the default environment variables list from the container image configuration.

        Args:
            image: Container image name or tar path.

        Returns:
            List of 'KEY=VALUE' environment variable strings.
        """
        pass

    @abstractmethod
    def create_oci_spec(
        self,
        image: str,
        container_cwd: str = "/",
        workdir_path: Optional[str] = None,
        env_dict: Optional[Dict[str, str]] = None,
        cpu: Optional[float] = None,
        memory: Optional[Union[str, int, float]] = None,
        readonly: bool = True,
        capabilities: Optional[List[str]] = None,
        network: str = "none",
        resolv_conf_source: Optional[str] = None,
        hosts_source: Optional[str] = None,
        base_spec: Optional[Dict[str, Any]] = None,
        root_path: Optional[str] = None,
        _oci_spec_transform_fn: Optional[Callable[[Dict], Optional[Dict]]] = None,
        disk: Optional[Union[str, int, float]] = None,
    ) -> Dict[str, Any]:
        """Construct an OCI container configuration specification dictionary.

        Args:
            image: Container image name or tar path.
            container_cwd: Working directory inside the container.
            workdir_path: Optional host directory to bind-mount read-write
                at container_cwd — the single writable path on a readonly
                rootfs. None mounts nothing.
            env_dict: Optional environment variables dictionary overriding image envs.
            cpu: CPU core allocation.
            memory: Memory allocation specifier.
            readonly: Whether rootfs is mounted read-only.
            capabilities: None keeps the runtime default; otherwise the
                bounding/effective/permitted sets are written exactly.
            network: Sandbox network mode; "host" and "public" drop the
                spec's empty network namespace.
            resolv_conf_source: Optional file to bind-mount read-only at
                /etc/resolv.conf.
            hosts_source: Optional file to bind-mount read-write at
                /etc/hosts (a per-sandbox copy, like the one container
                engines inject).
            base_spec: Optional base OCI spec dict to modify instead of generating a default.
            root_path: Host directory for ``root.path``. The rootfs itself
                comes from the gVisor annotations (the cached EROFS image);
                this directory only anchors the overlay's backing file.
                Defaults to a directory inside the image cache.
                For an overlayfs sandbox, the backend mounts the sandbox's
                kernel overlay on this directory, and the spec has no gVisor
                rootfs annotations.
            _oci_spec_transform_fn: Optional callback to transform the final spec.
            disk: Size cap of the writable rootfs overlay; None or zero
                means no cap. A capped writable overlay also holds the
                workdir, so ``workdir_path`` is then not mounted.

        Returns:
            Dictionary matching the OCI runtime-spec schema (config.json).
        """
        pass

    @abstractmethod
    def prepare_oci_bundle(
        self,
        root_dir: str,
        workdir_path: str,
        container_cwd: str,
        image: str,
        env_dict: Optional[Dict[str, str]] = None,
        cpu: Optional[float] = None,
        memory: Optional[Union[str, int, float]] = None,
        readonly: bool = True,
        capabilities: Optional[List[str]] = None,
        network: str = "none",
        dns: Optional[List[str]] = None,
        gpu_ids: Optional[List[str]] = None,
        _oci_spec_transform_fn: Optional[Callable[[Dict], Optional[Dict]]] = None,
        disk: Optional[Union[str, int, float]] = None,
    ) -> str:
        """Prepare an OCI bundle directory containing config.json for a container instance.

        Args:
            root_dir: Host directory for the container bundle.
            workdir_path: Optional host directory bind-mounted read-write at
                container_cwd (see create_oci_spec). None mounts nothing.
            container_cwd: Working directory inside container.
            image: Container image name or tar path.
            env_dict: Environment variables dictionary.
            cpu: CPU core allocation.
            memory: Memory allocation specifier.
            readonly: Read-only rootfs flag.
            capabilities: Optional additional Linux capabilities (see create_oci_spec).
            network: Sandbox network mode; picks the resolv.conf to mount
                ("public"/dns: generated, "host": the host's own).
            dns: Optional nameserver IPs for the generated resolv.conf.
            gpu_ids: Optional GPU device ids/UUIDs to expose via CDI.
            _oci_spec_transform_fn: Optional OCI spec transform function.
            disk: Size cap of the writable rootfs overlay (see
                create_oci_spec).

        Returns:
            Path to the written config.json file.
        """
        pass


class ImageManager(BaseImageManager):
    """Manages container image downloading, caching, metadata inspection, and OCI bundle creation."""

    def __init__(self, images_dir: str = DEFAULT_IMAGES_DIR):
        self._images_dir = images_dir
        # The mode of each image's latest pull in this process, so the spec
        # for a sandbox uses the rootfs its own pull pinned, even while
        # another mode's cache entry for the image exists.
        self._pull_modes: Dict[str, str] = {}
        # TODO: Send ReconcileImages here once the plugin socket appears, with
        # the leases the streamed entries' pins record. Every worker on the
        # node shares the cache, so that needs the image locks to not race
        # pulls in other workers.

    @property
    def images_dir(self) -> str:
        """Root directory for caching container images."""
        return self._images_dir

    def pull_image(
        self,
        image: str,
        timeout_seconds: float = 120.0,
        instance_id: Optional[str] = None,
    ) -> str:
        """Pull container image and extract rootfs into local images cache directory.

        The cache is bounded (see ``RAY_SANDBOX_IMAGE_CACHE_MAX_BYTES``);
        passing ``instance_id`` pins the image until ``release_image``.

        Args:
            image: Container image name (e.g. 'busybox:latest') or path to local tar archive.
            timeout_seconds: Timeout for network operations.
            instance_id: The sandbox instance that will use the image.

        If a node-local image provider plugin can stream the image (see
        ``image_provider_client``), the plugin mounts it and Ray caches only
        its metadata; each pin then holds one plugin lease. Otherwise, or with
        ``RAY_SANDBOX_IMAGE_STREAMING=disabled``, Ray pulls the image and
        builds an EROFS image of it. With ``RAY_SANDBOX_IMAGE_STREAMING=required``
        a registry image that can't be streamed fails instead.

        Returns:
            Absolute directory path containing the extracted container filesystem.

        Raises:
            SandboxCreationError: If the pull fails.
        """
        start = time.monotonic()
        streaming = image_provider.streaming_mode()
        if streaming != image_provider.STREAMING_DISABLED and not _is_local_archive(
            image
        ):
            try:
                image_dir, source, meta = self._pull_streamed_image(
                    image, timeout_seconds, instance_id
                )
            except image_provider.ImageProviderNotSupportedError as err:
                if streaming == image_provider.STREAMING_REQUIRED:
                    raise SandboxCreationError(
                        f"Image '{image}' can't be streamed, and "
                        f"{image_provider.STREAMING_MODE_ENV}=required: {err}"
                    ) from err
                logger.info(
                    "Not streaming image '%s' (%s); pulling it locally.", image, err
                )
            except image_provider.ImageProviderError as err:
                raise SandboxCreationError(
                    f"Image provider plugin failed to prepare '{image}': {err}"
                ) from err
            else:
                self._pull_modes[image] = MODE_STREAMED
                logger.info(
                    "image_pull mode=%s provider=%s image=%s ms=%.1f source=%s",
                    MODE_STREAMED,
                    meta.get("provider") or "unknown",
                    image,
                    (time.monotonic() - start) * 1000,
                    source,
                )
                return image_dir

        image_dir = pull_and_extract_container_image(
            image,
            images_dir=self._images_dir,
            timeout_seconds=timeout_seconds,
            instance_id=instance_id,
        )
        self._pull_modes[image] = MODE_EROFS
        logger.info(
            "image_pull mode=%s provider=local image=%s ms=%.1f",
            MODE_EROFS,
            image,
            (time.monotonic() - start) * 1000,
        )
        return image_dir

    def _pull_streamed_image(
        self,
        image: str,
        timeout_seconds: float,
        instance_id: Optional[str],
    ):
        """Pin a streamed image, taking a plugin lease unless the pin has one.

        A pin for ``instance_id`` that exists already has its lease. A pull
        with an instance claims the lease a pull without one left behind
        (the ``.unclaimed`` pin), and a pull without an instance takes a lease
        only if no pin holds one, so the image stays mounted until a sandbox
        claims it.

        Returns:
            The streamed cache entry's directory, how the pin was satisfied
            (``hit``, ``claim`` or ``prepare``), and the entry's metadata.

        Raises:
            ImageProviderNotSupportedError: To fall back to a local pull.
            ImageProviderError: If PrepareImage failed otherwise.
        """
        if not image_provider.available():
            raise image_provider.ImageProviderNotSupportedError(
                f"no image provider plugin at {image_provider.socket_path()}"
            )
        os.makedirs(self._images_dir, mode=0o777, exist_ok=True)
        streamed_dir = self.get_streamed_image_dir(image)
        users_dir = os.path.join(streamed_dir, _USERS_SUBDIR)
        unclaimed = os.path.join(users_dir, _UNCLAIMED_USER)
        pin = os.path.join(users_dir, instance_id or _UNCLAIMED_USER)
        # The lock eviction takes for this entry (see image_utils).
        with open(f"{streamed_dir}.lock", "w", encoding="utf-8") as f_lock:
            fcntl.flock(f_lock, fcntl.LOCK_EX)
            try:
                meta = self._read_streamed_metadata(streamed_dir, check_rootfs=True)
                if meta is not None:
                    if instance_id is None and _has_users(streamed_dir):
                        return streamed_dir, "hit", meta
                    if instance_id is not None and os.path.exists(pin):
                        return streamed_dir, "hit", meta
                    if instance_id is not None and os.path.exists(unclaimed):
                        os.replace(unclaimed, pin)
                        return streamed_dir, "claim", meta

                auth = image_provider.resolve_registry_auth(image)
                start = time.monotonic()
                try:
                    answer = image_provider.can_provide(image, auth=auth)
                except image_provider.ImageProviderNotSupportedError:
                    raise
                except image_provider.ImageProviderError as err:
                    raise image_provider.ImageProviderNotSupportedError(
                        str(err)
                    ) from err
                can_provide_ms = (time.monotonic() - start) * 1000
                if not answer.serving:
                    raise image_provider.ImageProviderNotSupportedError(
                        f"image provider {answer.provider_name!r} is not serving"
                    )
                if not answer.can_provide:
                    raise image_provider.ImageProviderNotSupportedError(
                        f"image provider {answer.provider_name!r} can't provide it"
                    )

                start = time.monotonic()
                prepared = image_provider.prepare_image(
                    image, auth=auth, timeout=timeout_seconds
                )
                prepare_ms = (time.monotonic() - start) * 1000
                try:
                    os.makedirs(streamed_dir, mode=0o755, exist_ok=True)
                    _write_json_atomic(
                        os.path.join(streamed_dir, _IMAGE_CONFIG_FILE), prepared.config
                    )
                    meta = {
                        "mode": MODE_STREAMED,
                        "image_ref": image,
                        "provider": prepared.provider_name or answer.provider_name,
                        "image_digest": prepared.image_digest,
                        "rootfs_dir": prepared.rootfs_dir,
                        "can_provide_ms": round(can_provide_ms, 3),
                        "prepare_ms": round(prepare_ms, 3),
                        "prepared_at": time.time(),
                    }
                    _write_json_atomic(
                        os.path.join(streamed_dir, STREAMED_MARKER), meta
                    )
                    # The pin records the reference its lease was taken
                    # with, which ReleaseImage must repeat exactly.
                    os.makedirs(users_dir, exist_ok=True)
                    with open(pin, "w", encoding="utf-8") as f_pin:
                        f_pin.write(image)
                except BaseException:
                    image_provider.release_image(image)
                    raise
                return streamed_dir, "prepare", meta
            finally:
                fcntl.flock(f_lock, fcntl.LOCK_UN)

    def release_image(self, image: str, instance_id: str) -> None:
        """Release an instance's pin on a cached image.

        A pin on a streamed image also releases its image provider lease.

        Args:
            image: Container image name or tar path passed to ``pull_image``.
            instance_id: The sandbox instance that no longer uses the image.
        """
        _release_image_use(self._erofs_image_dir(image), instance_id)
        pin = os.path.join(
            self.get_streamed_image_dir(image), _USERS_SUBDIR, instance_id
        )
        try:
            with open(pin, "r", encoding="utf-8") as f_pin:
                lease_ref = f_pin.read().strip() or image
            # Whoever removes the pin releases its lease, exactly once.
            os.remove(pin)
        except OSError:
            return
        image_provider.release_image(lease_ref)

    def get_streamed_image_dir(self, image: str) -> str:
        """The cache entry that holds a streamed image's metadata.

        Args:
            image: Container image name.

        Returns:
            Absolute directory path of the entry; it may not exist.
        """
        return os.path.join(
            self._images_dir, image_cache_name(image) + STREAMED_DIR_SUFFIX
        )

    def _erofs_image_dir(self, image: str) -> str:
        return os.path.join(self._images_dir, image_cache_name(image))

    @staticmethod
    def _read_streamed_metadata(
        streamed_dir: str, check_rootfs: bool = False
    ) -> Optional[Dict[str, Any]]:
        try:
            with open(
                os.path.join(streamed_dir, STREAMED_MARKER), "r", encoding="utf-8"
            ) as f:
                meta = json.load(f)
        except (OSError, ValueError):
            return None
        if not isinstance(meta, dict) or not meta.get("rootfs_dir"):
            return None
        if check_rootfs and not os.path.isdir(meta["rootfs_dir"]):
            return None
        return meta

    def image_mode(self, image: str) -> str:
        """Whether a sandbox on ``image`` boots from an EROFS image or a
        streamed directory.

        The mode of the image's latest pull in this process, else streamed if
        a streamed entry with a mounted rootfs exists and streaming isn't
        disabled.

        Args:
            image: Container image name or tar path.

        Returns:
            ``"erofs"`` or ``"streamed"``.
        """
        mode = self._pull_modes.get(image)
        if mode is not None:
            return mode
        if (
            not _is_local_archive(image)
            and image_provider.streaming_mode() != image_provider.STREAMING_DISABLED
            and self._read_streamed_metadata(
                self.get_streamed_image_dir(image), check_rootfs=True
            )
            is not None
        ):
            return MODE_STREAMED
        return MODE_EROFS

    def get_streamed_rootfs_dir(self, image: str) -> Optional[str]:
        """The host rootfs directory a sandbox on ``image`` boots from, if the
        image is streamed.

        Args:
            image: Container image name or tar path.

        Returns:
            The plugin's rootfs directory, or None for an EROFS image.
        """
        if self.image_mode(image) != MODE_STREAMED:
            return None
        meta = self._read_streamed_metadata(self.get_streamed_image_dir(image))
        return meta["rootfs_dir"] if meta else None

    def describe_image(self, image: str) -> Dict[str, Any]:
        """How ``image`` is cached, for benchmarks and debugging.

        Args:
            image: Container image name or tar path.

        Returns:
            ``mode``, ``provider``, ``digest``, ``rootfs`` (the streamed
            directory or the EROFS image), ``pins`` (instance ids, including
            ``.unclaimed``), ``prepare_ms`` and ``image_dir``.
        """
        mode = self.image_mode(image)
        image_dir = self.get_image_dir(image)
        try:
            pins = sorted(os.listdir(os.path.join(image_dir, _USERS_SUBDIR)))
        except OSError:
            pins = []
        info: Dict[str, Any] = {
            "mode": mode,
            "provider": None,
            "digest": None,
            "rootfs": None,
            "pins": pins,
            "prepare_ms": None,
            "image_dir": image_dir,
        }
        if mode == MODE_STREAMED:
            meta = self._read_streamed_metadata(image_dir) or {}
            info.update(
                provider=meta.get("provider"),
                digest=meta.get("image_digest"),
                rootfs=meta.get("rootfs_dir"),
                prepare_ms=meta.get("prepare_ms"),
            )
        else:
            erofs = os.path.join(image_dir, ROOTFS_IMAGE)
            info.update(
                provider="local", rootfs=erofs if os.path.isfile(erofs) else None
            )
        return info

    def get_image_dir(self, image: str) -> str:
        """Get the cached local directory path for an image.

        Args:
            image: Container image name or tar path.

        Returns:
            Absolute directory path for the image cache directory: the
            streamed entry if the image is streamed (see ``image_mode``),
            else the EROFS one.
        """
        if self.image_mode(image) == MODE_STREAMED:
            return self.get_streamed_image_dir(image)
        return self._erofs_image_dir(image)

    def get_rootfs_image(self, image: str) -> str:
        """Path of the cached image's EROFS root filesystem.

        Args:
            image: Container image name or tar path.

        Returns:
            Absolute path of the image's ``rootfs.erofs``.

        Raises:
            SandboxCreationError: If the image is not in the cache; call
                ``pull_image`` first.
        """
        path = os.path.join(self._erofs_image_dir(image), ROOTFS_IMAGE)
        if not os.path.isfile(path):
            raise SandboxCreationError(
                f"Image '{image}' has no cached root filesystem at {path}; "
                "pull it first."
            )
        return path

    def is_image_extracted(self, image: str) -> bool:
        """Check if an image has already been extracted to the local cache.

        Args:
            image: Container image name or tar path.

        Returns:
            True if image directory exists and contains .extracted marker,
            or the image is streamed and its rootfs is mounted.
        """
        if self.image_mode(image) == MODE_STREAMED:
            return (
                self._read_streamed_metadata(
                    self.get_streamed_image_dir(image), check_rootfs=True
                )
                is not None
            )
        img_dir = self._erofs_image_dir(image)
        marker = os.path.join(img_dir, ".extracted")
        return os.path.isdir(img_dir) and os.path.exists(marker)

    def get_image_config(self, image: str) -> Dict[str, Any]:
        """Read and parse the image configuration JSON (.image_config.json) if available.

        Args:
            image: Container image name or tar path.

        Returns:
            Dictionary representation of container image configuration.
        """
        img_dir = self.get_image_dir(image)
        config_path = os.path.join(img_dir, _IMAGE_CONFIG_FILE)
        if os.path.exists(config_path):
            try:
                with open(config_path, "r", encoding="utf-8") as f:
                    return json.load(f)
            except Exception as err:
                logger.warning(f"Failed to read image config at '{config_path}': {err}")
        return {}

    def get_workdir(self, image: str) -> Optional[str]:
        """Extract the default WorkingDir from the container image configuration.

        Args:
            image: Container image name or tar path.

        Returns:
            Configured working directory string, or None if not specified.
        """
        cfg = self.get_image_config(image)
        return cfg.get("config", {}).get("WorkingDir")

    def get_envs(self, image: str) -> List[str]:
        """Extract the default environment variables list from the container image configuration.

        Args:
            image: Container image name or tar path.

        Returns:
            List of 'KEY=VALUE' environment variable strings.
        """
        cfg = self.get_image_config(image)
        return cfg.get("config", {}).get("Env") or []

    def create_oci_spec(
        self,
        image: str,
        container_cwd: str = "/",
        workdir_path: Optional[str] = None,
        env_dict: Optional[Dict[str, str]] = None,
        cpu: Optional[float] = None,
        memory: Optional[Union[str, int, float]] = None,
        readonly: bool = True,
        capabilities: Optional[List[str]] = None,
        network: str = "none",
        resolv_conf_source: Optional[str] = None,
        hosts_source: Optional[str] = None,
        base_spec: Optional[Dict[str, Any]] = None,
        root_path: Optional[str] = None,
        _oci_spec_transform_fn: Optional[Callable[[Dict], Optional[Dict]]] = None,
        disk: Optional[Union[str, int, float]] = None,
    ) -> Dict[str, Any]:
        """Construct an OCI container configuration specification dictionary.

        Args:
            image: Container image name or tar path.
            container_cwd: Working directory inside the container.
            workdir_path: Optional host directory to bind-mount read-write
                at container_cwd — the single writable path on a readonly
                rootfs. None mounts nothing.
            env_dict: Optional environment variables dictionary overriding image envs.
            cpu: CPU core allocation.
            memory: Memory allocation specifier.
            readonly: Whether rootfs is mounted read-only.
            capabilities: None keeps the runtime default; otherwise the
                bounding/effective/permitted sets are written exactly.
            network: Sandbox network mode; "host" and "public" drop the
                spec's empty network namespace.
            resolv_conf_source: Optional file to bind-mount read-only at
                /etc/resolv.conf.
            hosts_source: Optional file to bind-mount read-write at
                /etc/hosts (a per-sandbox copy, like the one container
                engines inject).
            base_spec: Optional base OCI spec dict to modify instead of generating a default.
            root_path: Host directory for ``root.path``. The rootfs itself
                comes from the gVisor annotations (the cached EROFS image);
                this directory only anchors the overlay's backing file.
                Defaults to a directory inside the image cache.
                For an overlayfs sandbox, the backend mounts the sandbox's
                kernel overlay on this directory, and the spec has no gVisor
                rootfs annotations.
            _oci_spec_transform_fn: Optional callback to transform the final spec.
            disk: Size cap of the writable rootfs overlay; None or zero
                means no cap. A capped writable overlay also holds the
                workdir, so ``workdir_path`` is then not mounted.

        Returns:
            Dictionary matching the OCI runtime-spec schema (config.json).
        """
        spec = (
            copy.deepcopy(base_spec)
            if base_spec is not None
            else get_default_oci_spec()
        )

        # A streamed image's sandbox pulled it already, and holds its lease.
        streamed_rootfs = self._mounted_streamed_rootfs(image)
        if streamed_rootfs is not None:
            image_dir = self.get_streamed_image_dir(image)
        elif self._pull_modes.get(image) == MODE_EROFS:
            # Its sandbox pinned the EROFS image; don't ask the plugin.
            image_dir = pull_and_extract_container_image(
                image, images_dir=self._images_dir
            )
        else:
            image_dir = self.pull_image(image)
            streamed_rootfs = self._mounted_streamed_rootfs(image)
        erofs_image = os.path.join(image_dir, ROOTFS_IMAGE)
        if streamed_rootfs is None and not os.path.isfile(erofs_image):
            raise SandboxCreationError(
                f"Cached image '{image}' at {image_dir} has no {ROOTFS_IMAGE}; "
                "the cache entry is incomplete. Delete it to pull again."
            )
        spec.setdefault("root", {})
        # gVisor mounts the EROFS image inside the Sentry; root.path is only
        # the anchor under which the "self" overlay keeps the writable upper
        # layer's backing file, so make it per sandbox.
        rootfs = root_path or os.path.join(image_dir, "root")
        os.makedirs(rootfs, exist_ok=True)
        disk_bytes = parse_memory_bytes(disk) or 0
        if not readonly and disk_bytes > 0:
            # A bind-mounted host workdir would take writes past the cap,
            # so the workdir stays in the overlay (runsc creates it).
            workdir_path = None
        spec["root"]["path"] = rootfs
        spec["root"]["readonly"] = readonly

        spec.setdefault("process", {})
        spec["process"]["args"] = ["sleep", "infinity"]
        spec["process"]["cwd"] = container_cwd

        # Inherit Env from image config by default
        envs = list(self.get_envs(image))

        # User-provided envs override image envs
        if env_dict:
            filtered_envs = []
            for e in envs:
                key = e.split("=", 1)[0]
                if key not in env_dict:
                    filtered_envs.append(e)
            envs = filtered_envs
            for k, v in env_dict.items():
                envs.append(f"{k}={v}")
        spec["process"]["env"] = envs

        if capabilities is not None:
            # The key may exist with a null value in a caller-supplied base_spec.
            caps = spec["process"].get("capabilities")
            if not isinstance(caps, dict):
                caps = {}
                spec["process"]["capabilities"] = caps
            for cap_set in _OCI_CAPABILITY_SETS:
                # Written exactly (not unioned): [] runs with no capabilities.
                caps[cap_set] = list(dict.fromkeys(capabilities))

        # Set up default mounts
        mounts = spec.get("mounts", [])
        existing_dests = {m.get("destination") for m in mounts}

        if workdir_path:
            default_binds = [
                (container_cwd, workdir_path),
            ]
            for dest, src in default_binds:
                if dest != "/" and dest not in existing_dests and os.path.exists(src):
                    mounts.append(
                        {
                            "destination": dest,
                            "type": "bind",
                            "source": src,
                            "options": [
                                "rbind",
                                "rw" if dest == container_cwd else "ro",
                            ],
                        }
                    )
                    existing_dests.add(dest)
        if network in ("host", "public"):
            # The default spec carries an empty "network" namespace, which
            # would leave the sandbox loopback-only despite --network=host.
            # Drop it so the container inherits runsc's netns; a *pathed*
            # entry is somebody's explicit choice and is kept.
            linux_spec = spec.get("linux")
            if not isinstance(linux_spec, dict):
                linux_spec = {}
                spec["linux"] = linux_spec
            namespaces = linux_spec.get("namespaces")
            if isinstance(namespaces, list):
                linux_spec["namespaces"] = [
                    ns
                    for ns in namespaces
                    if not (
                        isinstance(ns, dict)
                        and ns.get("type") == "network"
                        and not ns.get("path")
                    )
                ]

        # Images usually ship an empty /etc/resolv.conf (container engines
        # inject one at run time); prepare_oci_bundle picks the file to mount.
        if resolv_conf_source and _RESOLV_CONF not in existing_dests:
            mounts.append(
                {
                    "destination": _RESOLV_CONF,
                    "type": "bind",
                    "source": resolv_conf_source,
                    "options": ["rbind", "ro"],
                }
            )
            existing_dests.add(_RESOLV_CONF)

        # Read-write like the file container engines inject; the source
        # is always a per-sandbox copy, never the node's own file.
        if hosts_source and _ETC_HOSTS not in existing_dests:
            mounts.append(
                {
                    "destination": _ETC_HOSTS,
                    "type": "bind",
                    "source": hosts_source,
                    "options": ["rbind", "rw"],
                }
            )
            existing_dests.add(_ETC_HOSTS)

        # Keep /tmp writable on a readonly rootfs, as it is under Docker.
        if readonly and "/tmp" not in existing_dests:
            mounts.append(
                {
                    "destination": "/tmp",
                    "type": "tmpfs",
                    "source": "tmpfs",
                    "options": ["nosuid", "nodev", "mode=1777"],
                }
            )
            existing_dests.add("/tmp")

        spec["mounts"] = mounts

        # Configure OCI cgroup resource limits for CPU and memory
        linux_sec = spec.setdefault("linux", {})
        resources = linux_sec.setdefault("resources", {})

        if cpu is not None and cpu > 0:
            period = 100000
            quota = int(cpu * period)
            cpu_res = resources.setdefault("cpu", {})
            cpu_res["period"] = period
            cpu_res["quota"] = quota

        parsed_mem = parse_memory_bytes(memory)
        if parsed_mem is not None and parsed_mem > 0:
            mem_res = resources.setdefault("memory", {})
            mem_res["limit"] = parsed_mem

        if _oci_spec_transform_fn:
            result = _oci_spec_transform_fn(spec)
            if result is not None:
                spec = result

        # runsc applies no overlay to a read-only root, and can't create mount
        # points in the image, so a readonly sandbox whose mounts need some
        # boots from a kernel overlay instead. A worker that can't mount one
        # runs it on a private writable overlay, whose writes are discarded
        # with it.
        if self._needs_writable_root_fallback(spec, streamed_rootfs):
            logger.warning(
                "readonly=True, but this worker can't mount an overlayfs rootfs, "
                "and runsc cannot create this sandbox's mount points in a "
                "read-only EROFS image, so it runs on a private writable overlay "
                "(its writes are discarded with it)."
            )
            spec["root"]["readonly"] = False

        # Only a sandbox that boots straight from the EROFS image needs the
        # gVisor rootfs annotations, and a writable one its private overlay.
        # Whether it does depends on the final spec, including anything the
        # transform added. An overlayfs sandbox instead runs on the kernel
        # overlay the backend mounts at root.path, over the EROFS image or
        # the streamed rootfs directory.
        if not overlayfs.needs_rootfs_overlay_for_image(spec, streamed_rootfs):
            annotations = spec.setdefault("annotations", {})
            if streamed_rootfs is not None:
                # gVisor binds the plugin's read-only directory as the root.
                # It needs both the source and the type, and the writable
                # layer goes in memory: "self" would put its backing file in
                # the read-only directory.
                spec["root"]["path"] = streamed_rootfs
                annotations["dev.gvisor.spec.rootfs.source"] = streamed_rootfs
                annotations["dev.gvisor.spec.rootfs.type"] = "bind"
                overlay_medium = "memory"
            else:
                annotations["dev.gvisor.spec.rootfs.source"] = erofs_image
                annotations["dev.gvisor.spec.rootfs.type"] = "erofs"
                overlay_medium = "self"
            if not spec["root"].get("readonly"):
                annotations["dev.gvisor.spec.rootfs.overlay"] = overlay_medium
                if disk_bytes > 0:
                    # gVisor sizes the overlay's upper layer from this
                    # annotation, so writes past it fail with ENOSPC. The
                    # --overlay2 flag's size doesn't apply to a rootfs that
                    # annotations configure.
                    annotations["dev.gvisor.spec.rootfs.options"] = f"size={disk_bytes}"

        return spec

    def _mounted_streamed_rootfs(self, image: str) -> Optional[str]:
        if self.image_mode(image) != MODE_STREAMED:
            return None
        meta = self._read_streamed_metadata(
            self.get_streamed_image_dir(image), check_rootfs=True
        )
        return meta["rootfs_dir"] if meta else None

    @staticmethod
    def _needs_writable_root_fallback(
        spec: Dict[str, Any], rootfs_dir: Optional[str] = None
    ) -> bool:
        """Whether a readonly sandbox needs a writable root to boot.

        Args:
            spec: The final OCI spec.
            rootfs_dir: The streamed rootfs directory, or None for an EROFS
                image.

        Returns:
            True if the root is read-only, the spec has no hooks that need a
            kernel overlay, some of the spec's mounts need mount points the
            image may not have, and this worker can't mount a kernel overlay to
            create them.
        """
        if not spec["root"].get("readonly"):
            return False
        if overlayfs.has_prestart_hooks(spec):
            return False
        missing = (
            overlayfs.missing_mount_points(spec)
            if rootfs_dir is None
            else overlayfs.missing_mount_points(spec, rootfs_dir)
        )
        if len(missing) == 0:
            return False
        if overlayfs.can_mount_rootfs_overlay():
            return False
        return True

    def prepare_oci_bundle(
        self,
        root_dir: str,
        workdir_path: str,
        container_cwd: str,
        image: str,
        env_dict: Optional[Dict[str, str]] = None,
        cpu: Optional[float] = None,
        memory: Optional[Union[str, int, float]] = None,
        readonly: bool = True,
        capabilities: Optional[List[str]] = None,
        network: str = "none",
        dns: Optional[List[str]] = None,
        gpu_ids: Optional[List[str]] = None,
        _oci_spec_transform_fn: Optional[Callable[[Dict], Optional[Dict]]] = None,
        disk: Optional[Union[str, int, float]] = None,
    ) -> str:
        """Prepare an OCI bundle directory containing config.json for a container instance.

        Args:
            root_dir: Host directory for the container bundle.
            workdir_path: Optional host directory bind-mounted read-write at
                container_cwd (see create_oci_spec). None mounts nothing.
            container_cwd: Working directory inside container.
            image: Container image name or tar path.
            env_dict: Environment variables dictionary.
            cpu: CPU core allocation.
            memory: Memory allocation specifier.
            readonly: Read-only rootfs flag.
            capabilities: Optional additional Linux capabilities (see create_oci_spec).
            network: Sandbox network mode; picks the resolv.conf to mount
                ("public"/dns: generated, "host": the host's own).
            dns: Optional nameserver IPs for the generated resolv.conf.
            gpu_ids: Optional GPU device ids/UUIDs to expose via CDI.
            _oci_spec_transform_fn: Optional OCI spec transform function.
            disk: Size cap of the writable rootfs overlay (see
                create_oci_spec).

        Returns:
            Path to the written config.json file.
        """
        config_json_path = os.path.join(root_dir, "config.json")
        rootfs_dir = os.path.join(root_dir, "rootfs")
        os.makedirs(rootfs_dir, exist_ok=True)

        resolv_conf_source: Optional[str] = None
        if network in ("public", "host"):
            nameservers = list(dns) if dns else None
            if network == "public" and nameservers is None:
                nameservers = list(DEFAULT_PUBLIC_DNS)
            if nameservers is not None:
                # Generated and host-independent: no search domains, resolver
                # VIPs, or ndots options leak in from the host.
                resolv_conf_source = os.path.join(root_dir, "resolv.conf")
                with open(resolv_conf_source, "w", encoding="utf-8") as f:
                    f.write("".join(f"nameserver {ip}\n" for ip in nameservers))
            elif os.path.exists(_RESOLV_CONF):
                resolv_conf_source = _RESOLV_CONF

        # Engines inject /etc/hosts at run time; without it `localhost`
        # does not resolve. Host networking also inherits the node's entries.
        hosts_source = os.path.join(root_dir, "hosts")
        host_entries = ""
        if network == "host" and os.path.exists(_ETC_HOSTS):
            try:
                with open(_ETC_HOSTS, "r", encoding="utf-8", errors="replace") as f:
                    host_entries = f.read()
            except OSError:
                host_entries = ""
        with open(hosts_source, "w", encoding="utf-8") as f:
            f.write("127.0.0.1\tlocalhost\n")
            f.write("::1\tlocalhost ip6-localhost ip6-loopback\n")
            if host_entries:
                f.write(host_entries)

        if gpu_ids:
            cdi_spec = cdi.require_spec("GPU")
            try:
                cdi_devices = cdi_spec.select_devices(gpu_ids)
            except cdi_lib.CDIError as err:
                raise SandboxCreationError(
                    f"Failed to configure GPU access via CDI: {err}"
                ) from err
            gpu_cdi_devices_fn = _build_gpu_cdi_devices_transform_fn(
                cdi_spec, cdi_devices
            )
            _oci_spec_transform_fn = _chain_transform_fns(
                gpu_cdi_devices_fn, _oci_spec_transform_fn
            )

        spec = self.create_oci_spec(
            image=image,
            container_cwd=container_cwd,
            workdir_path=workdir_path,
            env_dict=env_dict,
            cpu=cpu,
            memory=memory,
            readonly=readonly,
            capabilities=capabilities,
            network=network,
            resolv_conf_source=resolv_conf_source,
            hosts_source=hosts_source,
            root_path=rootfs_dir,
            _oci_spec_transform_fn=_oci_spec_transform_fn,
            disk=disk,
        )

        config_json_str = json.dumps(spec, indent=2)
        with open(config_json_path, "w", encoding="utf-8") as f:
            f.write(config_json_str)

        return config_json_path
